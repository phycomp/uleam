# 2. 核心：N通道多導體傳輸線 (MTL) 大型矩陣求解器
# ==============================================================================
def build_n_channel_matrices(n, w, s, h, t, dk, df, freq):
    """
    動態建構 N 通道平行總線的 N x N 大型 Maxwell 互容、互感、電阻與電導矩陣
    """
    w_m, s_m, h_m, t_m = w*1e-6, s*1e-6, h*1e-6, t*1e-6
    omega = 2 * pi * freq
    
    # 1. 建立電容矩陣 C (考慮鄰近與次鄰近通道的麥克斯韋電容衰減)
    C = zeros((n, n))
    c_self = 8.854e-12 * dk * (w_m / h_m + 1.2)
    for i in range(n):
        for j in range(n):
            if i == j:
                C[i, j] = c_self
            else:
                dist_factor = abs(i - j)
                # 耦合隨距離指數級或立方級衰減
                c_mutual = (8.854e-12 * dk * 0.4) / ((dist_factor * (s_m + w_m) / h_m) + 0.05)
                C[i, j] = -c_mutual
        # 麥克斯韋矩陣修正：對角線為自容加上所有與他人之互容絕對值
        C[i, i] = C[i, i] - sum(C[i, :]) + C[i, i]

    # 2. 建立電感矩陣 L (基於自由空間光速與電容逆矩陣關係)
    C_vacuum = C / dk
    L = (1.256e-6 * 8.854e-12) * linalg.inv(C_vacuum)
    
    # 3. 建立損耗矩陣 R 與 G
    r_skin = 1.0 / (5.8e7 * t_m * w_m) * sqrt(freq / 1e9)
    R = eye(n) * r_skin
    G = omega * C * df * 0.1
    
    return R, L, G, C

def solve_mtl_crosstalk(R, L, G, C, freq, length, agg_idx):
    """
    全 N 通道矩陣電報方程解算
    """
    n = R.shape[0]
    omega = 2 * pi * freq
    Z_mat = R + 1j * omega * L
    Y_mat = G + 1j * omega * C
    
    # 計算矩陣複數傳播常數
    YZ = dot(Y_mat, Z_mat)
    evals, evecs = linalg.eig(YZ)
    gamma_mat = dot(evecs, dot(diag(sqrt(evals)), linalg.inv(evecs)))
    
    # 轉移矩陣 (傳播矩陣)
    T_mat = expm(-gamma_mat * length)
    
    # 激勵向量：假定主動線 (Aggressor) 輸入 1V 電壓波
    V_in = zeros(n, dtype=complex)
    V_in[agg_idx] = 1.0
    
    V_out = dot(T_mat, V_in)
    
    # 計算各通道的串擾分貝值 (相較於主動線輸入)
    xtalk_db = 20 * log10(abs(V_out) + 1e-9)
    return xtalk_db

