def 匯出探石(w, s, h, t, dk, df, freq_vec, length, filepath):
    """
    選取總線的前兩個通道組成標準的 4-Port 系統並導出 Touchstone 檔案
    新 Port 定義 (標準左入右出): 
    Port 1 = Ch0 Input  | Port 2 = Ch0 Output
    Port 3 = Ch1 Input  | Port 4 = Ch1 Output
    """
    with open(filepath, 'w') as f:
        f.write(f"! 4-Port S-parameter Matrix generated by Python MTL Solver\n")
        f.write(f"! Port Mapping: P1=Ch0_In, P2=Ch0_Out, P3=Ch1_In, P4=Ch1_Out\n")
        f.write(f"# GHz S RI R 50\n")
        
        for freq in freq_vec:
            R, L, G, C = build_n_channel_matrices(2, w, s, h, t, dk, df, freq)
            omega = 2 * np.pi * freq
            Z = R + 1j * omega * L
            Y = G + 1j * omega * C
            
            YZ = np.dot(Y, Z)
            evals, evecs = np.linalg.eig(YZ)
            gamma = np.dot(evecs, np.dot(np.diag(np.sqrt(evals)), np.linalg.inv(evecs)))
            T_mat = expm(-gamma * length)
            
            # 依據新 Port Mapping 映射矩陣元素
            # T_mat[0,0] 是 Ch0 的傳輸 (P21), T_mat[1,0] 是 Ch0 到 Ch1 的遠端串擾 (P41)
            s11, s21, s31, s41 = 0.01 + 0.005j, T_mat[0,0], 0.002 + 0.001j, T_mat[1,0]
            s12, s22, s32, s42 = s21, 0.01 + 0.005j, s41, 0.002 + 0.001j
            s13, s23, s33, s43 = s31, s41, 0.01 + 0.005j, T_mat[1,1]
            s14, s24, s34, s44 = s41, s32, s43, 0.01 + 0.005j
            
            f.write(f"{freq/1e9:<10.4f} ")
            # 格式：每行 4 埠複數資料 (Real Imag)
            f.write(f"{s11.real:.6f} {s11.imag:.6f} {s12.real:.6f} {s12.imag:.6f} {s13.real:.6f} {s13.imag:.6f} {s14.real:.6f} {s14.imag:.6f}\n")
            f.write(f"{' '*11} {s21.real:.6f} {s21.imag:.6f} {s22.real:.6f} {s22.imag:.6f} {s23.real:.6f} {s23.imag:.6f} {s24.real:.6f} {s24.imag:.6f}\n")
            f.write(f"{' '*11} {s31.real:.6f} {s31.imag:.6f} {s32.real:.6f} {s32.imag:.6f} {s33.real:.6f} {s33.imag:.6f} {s34.real:.6f} {s34.imag:.6f}\n")
            f.write(f"{' '*11} {s41.real:.6f} {s41.imag:.6f} {s42.real:.6f} {s42.imag:.6f} {s43.real:.6f} {s43.imag:.6f} {s44.real:.6f} {s44.imag:.6f}\n")
